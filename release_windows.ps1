# Packages the Windows bundle for a GitHub release, the layout Popcorn.Installer looks for:
#   tag v<version>, assets Popcorn-<version>-windows-x64.zip (Bundle/Windows contents, release.json at the root)
#   + Popcorn.Installer.exe (the same installer standalone: what a new user downloads to install Popcorn).
# No checksum file: the installer checks the download against the SHA-256 digest GitHub computes on upload. Each
# platform's script uploads only its own files (release_linux.sh: the Linux ones), so the platforms can be built and
# published from different machines into the same release.
# Output: Bundle/Release/<version>/. -Publish then creates the release with the GitHub CLI (gh, logged in), or
# uploads the files into an existing one.
#   .\release_windows.ps1                       # build_windows.ps1 with the VERSION file's version + package
#   .\release_windows.ps1 -Version 1.2.0 -Publish -Draft
#   .\release_windows.ps1 -SkipBuild            # package the existing Bundle/Windows
# Test a package without publishing: Popcorn.Installer.exe --package Bundle\Release\<version>\Popcorn-<version>-windows-x64.zip
param(
    [string]$Version,
    [switch]$SkipBuild,
    [string]$BundleDir = (Join-Path $PSScriptRoot "Bundle\Windows"),
    [string]$OutputDir = (Join-Path $PSScriptRoot "Bundle\Release"),
    [switch]$Publish,
    [string]$Repo = $env:POPCORN_UPDATE_REPO, # owner/name; empty = the checkout's GitHub remote (gh's default)
    [switch]$Draft,
    [switch]$Prerelease,
    [string]$NotesFile                        # release notes (markdown); default: generated by GitHub
)
$ErrorActionPreference = "Stop"
$Platform = "windows-x64"

function Invoke-Native {
    param ([string]$exe, [Parameter(ValueFromRemainingArguments)][string[]]$arguments)
    $ErrorActionPreference = "Continue"
    & $exe @arguments
    if ($LASTEXITCODE -ne 0) {
        throw "'$exe $arguments' failed with exit code $LASTEXITCODE"
    }
}

if (!$Version) {
    $Version = (Get-Content -Raw -Path (Join-Path $PSScriptRoot "VERSION")).Trim()
}
if ($Version -notmatch '^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$') {
    throw "Version '$Version' is not major.minor.patch[-prerelease]"
}
$Tag = "v$Version"

if (!$SkipBuild) {
    & (Join-Path $PSScriptRoot "build_windows.ps1") -Version $Version
}

# The bundle must be what the installer expects to install.
$ManifestPath = Join-Path $BundleDir "release.json"
if (!(Test-Path $ManifestPath)) {
    throw "$ManifestPath missing, build with build_windows.ps1 first"
}
$Manifest = Get-Content -Raw -Path $ManifestPath | ConvertFrom-Json
if ($Manifest.version -ne $Version -or $Manifest.platform -ne $Platform) {
    throw "$ManifestPath is $($Manifest.version) $($Manifest.platform), expected $Version $Platform (rebuild, or drop -SkipBuild)"
}
foreach ($required in "Popcorn.Server.exe", "Popcorn.Windows.exe", "Popcorn.Installer.exe", "Player\libmpv-2.dll") {
    if (!(Test-Path (Join-Path $BundleDir $required))) {
        # Without the installer in it, installs of this release could not update themselves any more.
        throw "$required missing from $BundleDir"
    }
}

$ReleaseDir = Join-Path $OutputDir $Version
New-Item -ItemType Directory -Force -Path $ReleaseDir | Out-Null
$ZipName = "Popcorn-$Version-$Platform.zip"
$ZipPath = Join-Path $ReleaseDir $ZipName
if (Test-Path $ZipPath) {
    Remove-Item -Force $ZipPath
}

# Entries one by one: forward slashes in the names (Compress-Archive in Windows PowerShell writes backslashes).
Write-Output "Packing $BundleDir -> $ZipPath"
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
$Root = (Resolve-Path $BundleDir).Path.TrimEnd('\') + '\'
$Zip = [System.IO.Compression.ZipFile]::Open($ZipPath, [System.IO.Compression.ZipArchiveMode]::Create)
try {
    foreach ($file in Get-ChildItem -Recurse -File -Path $Root) {
        $entryName = $file.FullName.Substring($Root.Length).Replace('\', '/')
        [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile(
            $Zip, $file.FullName, $entryName, [System.IO.Compression.CompressionLevel]::Optimal) | Out-Null
    }
} finally {
    $Zip.Dispose()
}

# The bundle's installer also on its own: downloaded by itself it installs Popcorn (see Popcorn.Installer/README.md).
$InstallerName = "Popcorn.Installer.exe"
$InstallerPath = Join-Path $ReleaseDir $InstallerName
Copy-Item -Force -Path (Join-Path $BundleDir $InstallerName) -Destination $InstallerPath

$Assets = @($ZipPath, $InstallerPath)
Write-Output "Release files:"
$Assets | ForEach-Object { Write-Output "  $(Split-Path -Leaf $_)" }

if (!$Publish) {
    Write-Output "Release files in $ReleaseDir (publish with -Publish)"
    return
}

if (!(Get-Command gh -ErrorAction SilentlyContinue)) {
    throw "gh (GitHub CLI) not found on PATH: https://cli.github.com, then 'gh auth login'"
}
$RepoArgs = @()
if ($Repo) {
    $RepoArgs = @("--repo", $Repo)
}

$ErrorActionPreference = "Continue"
& gh release view $Tag @RepoArgs *> $null
$Exists = $LASTEXITCODE -eq 0
$ErrorActionPreference = "Stop"

if ($Exists) {
    Write-Output "Release $Tag exists, uploading the files into it"
    Invoke-Native gh release upload $Tag @Assets --clobber @RepoArgs
} else {
    if (git status --porcelain) {
        Write-Warning "The working tree has uncommitted changes; the tag points at HEAD without them"
    }
    $CreateArgs = @($Tag) + $Assets + @("--title", "Popcorn $Version", "--target", (git rev-parse HEAD).Trim()) + $RepoArgs
    if ($NotesFile) { $CreateArgs += @("--notes-file", $NotesFile) } else { $CreateArgs += "--generate-notes" }
    if ($Draft) { $CreateArgs += "--draft" }
    if ($Prerelease) { $CreateArgs += "--prerelease" }
    Invoke-Native gh release create @CreateArgs
}
Write-Output "Published $Tag"
