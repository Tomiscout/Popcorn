#!/usr/bin/env bash
# Packages the Linux bundle for a GitHub release, the layout Popcorn.Installer looks for (release_windows.ps1's
# counterpart; both can publish into the same v<version> release):
#   tag v<version>, assets Popcorn-<version>-linux-x64.zip (Bundle/Linux contents, release.json at the root, Unix modes
#   kept: the installer restores them)
#   + Popcorn.Installer.Linux (the same installer standalone: what a new user downloads to install Popcorn; next to
#   Windows' Popcorn.Installer.exe in the same release).
# No checksum file: the installer checks the download against the SHA-256 digest GitHub computes on upload. Each
# platform's script uploads only its own files, so Windows and Linux can be built and published from different
# machines into the same release.
# Output: Bundle/Release/<version>/ (shared with release_windows.ps1). --publish then creates the release with the GitHub CLI (gh, logged in), or uploads
# the files into an existing one.
#   ./release_linux.sh                          # make all with the VERSION file's version + package
#   ./release_linux.sh --version 1.2.0 --publish --draft
#   ./release_linux.sh --skip-build             # package the existing Bundle/Linux
# Test a package without publishing:
#   Bundle/Linux/Popcorn.Installer.Linux --package Bundle/Release/<version>/Popcorn-<version>-linux-x64.zip
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VERSION=""
SKIP_BUILD=0
BUNDLE_DIR="$ROOT/Bundle/Linux"
OUTPUT_DIR="$ROOT/Bundle/Release"
PUBLISH=0
REPO="${POPCORN_UPDATE_REPO:-}" # owner/name; empty = the checkout's GitHub remote (gh's default)
DRAFT=0
PRERELEASE=0
NOTES_FILE=""                   # release notes (markdown); default: generated by GitHub

usage() {
    sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//'
    echo
    echo "Options: --version <x.y.z> --skip-build --bundle-dir <dir> --output-dir <dir> --publish --repo <owner/name>"
    echo "         --draft --prerelease --notes-file <file>"
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --version) VERSION="$2"; shift 2 ;;
        --skip-build) SKIP_BUILD=1; shift ;;
        --bundle-dir) BUNDLE_DIR="$(realpath -m "$2")"; shift 2 ;;
        --output-dir) OUTPUT_DIR="$(realpath -m "$2")"; shift 2 ;;
        --publish) PUBLISH=1; shift ;;
        --repo) REPO="$2"; shift 2 ;;
        --draft) DRAFT=1; shift ;;
        --prerelease) PRERELEASE=1; shift ;;
        --notes-file) NOTES_FILE="$(realpath "$2")"; shift 2 ;;
        -h|--help) usage; exit 0 ;;
        *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
    esac
done

fail() {
    echo "error: $*" >&2
    exit 1
}

case "$(uname -m)" in
    x86_64) PLATFORM="linux-x64" ;;
    aarch64|arm64) PLATFORM="linux-arm64" ;;
    *) fail "unsupported architecture $(uname -m)" ;;
esac

if [[ -z "$VERSION" ]]; then
    VERSION="$(tr -d '[:space:]' < "$ROOT/VERSION")"
fi
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]] || fail "version '$VERSION' is not major.minor.patch[-prerelease]"
TAG="v$VERSION"

command -v python3 >/dev/null || fail "python3 not found (packs the zip with the files' Unix modes)"

if [[ $SKIP_BUILD -eq 0 ]]; then
    make -C "$ROOT" all VERSION="$VERSION"
fi

# The bundle must be what the installer expects to install.
MANIFEST="$BUNDLE_DIR/release.json"
[[ -f "$MANIFEST" ]] || fail "$MANIFEST missing, build with 'make all' first"
read -r MANIFEST_VERSION MANIFEST_PLATFORM < <(python3 -I -c '
import json, sys
m = json.load(open(sys.argv[1], encoding="utf-8-sig"))
print(m.get("version", ""), m.get("platform", ""))' "$MANIFEST")
if [[ "$MANIFEST_VERSION" != "$VERSION" || "$MANIFEST_PLATFORM" != "$PLATFORM" ]]; then
    fail "$MANIFEST is $MANIFEST_VERSION $MANIFEST_PLATFORM, expected $VERSION $PLATFORM (rebuild, or drop --skip-build)"
fi
for required in Popcorn.Server Popcorn.Linux Popcorn.Player.Linux Popcorn.Installer.Linux libpopcorn_player.so \
        popcorn-player-cef libcef.so setup/popcorn.service setup/popcorn.desktop; do
    # Without the installer in it, installs of this release could not update themselves any more.
    [[ -e "$BUNDLE_DIR/$required" ]] || fail "$required missing from $BUNDLE_DIR"
done
for executable in Popcorn.Server Popcorn.Linux Popcorn.Player.Linux Popcorn.Installer.Linux popcorn-player-cef; do
    [[ -x "$BUNDLE_DIR/$executable" ]] || fail "$BUNDLE_DIR/$executable is not executable"
done
if [[ ! -e "$BUNDLE_DIR/libmpv.so.2" ]]; then
    echo "warning: no libmpv.so.2 in the bundle (make mpv): the player uses the system libmpv, without DMA-BUF video" >&2
fi

RELEASE_DIR="$OUTPUT_DIR/$VERSION"
mkdir -p "$RELEASE_DIR"
ZIP_NAME="Popcorn-$VERSION-$PLATFORM.zip"
ZIP_PATH="$RELEASE_DIR/$ZIP_NAME"
rm -f "$ZIP_PATH"

# Python's zipfile stores each file's mode (external attributes), which Popcorn.Installer applies on Linux; symlinks
# are stored as the files they point to. Sorted entries: the same bundle gives the same file list.
echo "Packing $BUNDLE_DIR -> $ZIP_PATH"
python3 -I - "$BUNDLE_DIR" "$ZIP_PATH" <<'EOF'
import os, sys, zipfile
root, out = sys.argv[1], sys.argv[2]
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
    for folder, dirs, files in os.walk(root, followlinks=True):
        dirs.sort()
        for name in sorted(files):
            path = os.path.join(folder, name)
            archive.write(path, os.path.relpath(path, root).replace(os.sep, "/"))
EOF

# The bundle's installer also on its own: downloaded by itself it installs Popcorn (see Popcorn.Installer/README.md).
INSTALLER_NAME="Popcorn.Installer.Linux"
INSTALLER_PATH="$RELEASE_DIR/$INSTALLER_NAME"
install -m 755 "$BUNDLE_DIR/$INSTALLER_NAME" "$INSTALLER_PATH"

ASSETS=("$ZIP_PATH" "$INSTALLER_PATH")
echo "Release files:"
for file in "${ASSETS[@]}"; do echo "  $(basename "$file")"; done
if [[ $PUBLISH -eq 0 ]]; then
    echo "Release files in $RELEASE_DIR (publish with --publish)"
    exit 0
fi

command -v gh >/dev/null || fail "gh (GitHub CLI) not found on PATH: https://cli.github.com, then 'gh auth login'"
REPO_ARGS=()
if [[ -n "$REPO" ]]; then
    REPO_ARGS=(--repo "$REPO")
fi

if gh release view "$TAG" "${REPO_ARGS[@]}" >/dev/null 2>&1; then
    echo "Release $TAG exists, uploading the files into it"
    gh release upload "$TAG" "${ASSETS[@]}" --clobber "${REPO_ARGS[@]}"
else
    if [[ -n "$(git -C "$ROOT" status --porcelain)" ]]; then
        echo "warning: the working tree has uncommitted changes; the tag points at HEAD without them" >&2
    fi
    CREATE_ARGS=("$TAG" "${ASSETS[@]}" --title "Popcorn $VERSION"
        --target "$(git -C "$ROOT" rev-parse HEAD)" "${REPO_ARGS[@]}")
    if [[ -n "$NOTES_FILE" ]]; then CREATE_ARGS+=(--notes-file "$NOTES_FILE"); else CREATE_ARGS+=(--generate-notes); fi
    if [[ $DRAFT -eq 1 ]]; then CREATE_ARGS+=(--draft); fi
    if [[ $PRERELEASE -eq 1 ]]; then CREATE_ARGS+=(--prerelease); fi
    gh release create "${CREATE_ARGS[@]}"
fi
echo "Published $TAG"
