//! Release files of the host platform, the layout Popcorn.Installer looks for:
//!   tag v<version>, assets Popcorn-<version>-<platform>.zip (the bundle, release.json at the root; Unix modes kept on
//!   Linux, the installer restores them) + the installer on its own (Popcorn.Installer.Linux / Popcorn.Installer.exe:
//!   what a new user downloads to install Popcorn).
//! No checksum file: the installer checks the download against the SHA-256 digest GitHub computes on upload. Only the
//! host platform's files are uploaded, so Linux and Windows publish into the same release from different machines.
//! Test a package without publishing: `<bundle>/Popcorn.Installer.Linux --package Bundle/Release/<v>/<zip>`.

use std::fs::{self, File};
use std::io;
use std::path::{Path, PathBuf};

use anyhow::{Context as _, Result};
use zip::write::SimpleFileOptions;

use crate::util::{bundle_dir, cmd, files, has, output, path, release_platform, run, step, version, warn};
use crate::{BuildOptions, build, bundle};

#[derive(clap::Args)]
pub struct Options {
    #[command(flatten)]
    build: BuildOptions,
    /// Package the existing bundle
    #[arg(long)]
    skip_build: bool,
    /// Create the v<version> GitHub release with gh (logged in), or upload into the existing one
    #[arg(long)]
    publish: bool,
    /// owner/name; default: the checkout's GitHub remote (gh's default)
    #[arg(long, env = "POPCORN_UPDATE_REPO")]
    repo: Option<String>,
    #[arg(long)]
    draft: bool,
    #[arg(long)]
    prerelease: bool,
    /// Release notes (markdown); default: generated by GitHub
    #[arg(long)]
    notes_file: Option<PathBuf>,
}

fn installer_name() -> &'static str {
    if cfg!(windows) { "Popcorn.Installer.exe" } else { "Popcorn.Installer.Linux" }
}

pub fn release(options: &Options) -> Result<()> {
    let version = version(options.build.version.as_deref())?;
    if !options.skip_build {
        bundle::bundle(&build::Context::new(&options.build)?)?;
    }
    let bundle = bundle_dir();
    bundle::verify(&bundle, &version)?;

    step("Release files");
    let dir = path("Bundle/Release").join(&version);
    fs::create_dir_all(&dir)?;
    let zip_path = dir.join(format!("Popcorn-{version}-{}.zip", release_platform()));
    println!("Packing {} -> {}", bundle.display(), zip_path.display());
    pack(&bundle, &zip_path)?;
    let installer = dir.join(installer_name());
    fs::copy(bundle.join(installer_name()), &installer)?;
    let assets = [zip_path, installer];
    for asset in &assets {
        println!("  {}", asset.display());
    }
    if !options.publish {
        println!("Not published (--publish)");
        return Ok(());
    }
    publish(options, &version, &assets)
}

/// The bundle as a zip with forward slashes, entries sorted (the same bundle gives the same file list), Unix modes in
/// the entries on Linux; symlinks stored as the files they point to.
fn pack(bundle: &Path, zip_path: &Path) -> Result<()> {
    let _ = fs::remove_file(zip_path);
    let mut zip = zip::ZipWriter::new(File::create(zip_path)?);
    for file in files(bundle)? {
        let source = bundle.join(&file);
        let name = file.components().map(|c| c.as_os_str().to_string_lossy()).collect::<Vec<_>>().join("/");
        #[allow(unused_mut)]
        let mut options = SimpleFileOptions::default()
            .compression_method(zip::CompressionMethod::Deflated)
            .compression_level(Some(9));
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            options = options.unix_permissions(fs::metadata(&source)?.permissions().mode() & 0o777);
        }
        zip.start_file(name, options)?;
        io::copy(&mut File::open(&source).with_context(|| format!("reading {}", source.display()))?, &mut zip)?;
    }
    zip.finish()?;
    Ok(())
}

fn publish(options: &Options, version: &str, assets: &[PathBuf]) -> Result<()> {
    if !has("gh") {
        anyhow::bail!("gh (GitHub CLI) not found on PATH: https://cli.github.com, then `gh auth login`");
    }
    let tag = format!("v{version}");
    let repo: Vec<&str> = options.repo.as_deref().map(|r| vec!["--repo", r]).unwrap_or_default();
    let exists = cmd("gh").args(["release", "view", &tag]).args(&repo).output().is_ok_and(|o| o.status.success());
    if exists {
        println!("Release {tag} exists, uploading the files into it");
        run(cmd("gh").args(["release", "upload", &tag]).args(assets).arg("--clobber").args(&repo))?;
    } else {
        if !output(cmd("git").args(["status", "--porcelain"]))?.is_empty() {
            warn("the working tree has uncommitted changes; the tag points at HEAD without them");
        }
        let head = output(cmd("git").args(["rev-parse", "HEAD"]))?;
        let mut create = cmd("gh");
        create.args(["release", "create", &tag]).args(assets);
        create.args(["--title", &format!("Popcorn {version}"), "--target", &head]).args(&repo);
        match &options.notes_file {
            Some(notes) => create.arg("--notes-file").arg(notes),
            None => create.arg("--generate-notes"),
        };
        if options.draft {
            create.arg("--draft");
        }
        if options.prerelease {
            create.arg("--prerelease");
        }
        run(&mut create)?;
    }
    println!("Published {tag}");
    Ok(())
}
